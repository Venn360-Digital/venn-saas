#!/usr/bin/env bash
# Build /opt/app/odontobox360/.env from the credentials the host already holds.
#
# Run on the VPS. Reads the existing stack's .env so no secret ever has to be
# typed, pasted or carried anywhere: the Supabase keys, both database passwords
# and the Redis password are taken from the file that already has them.
#
# Safe to re-run: it regenerates the file from the current source of truth. The
# only value it invents is the Evolution Go API key, and only on first run.
set -euo pipefail

SRC="${SRC:-/opt/app/compose/.env}"
DEST_DIR="${DEST_DIR:-/opt/app/odontobox360}"
DEST="$DEST_DIR/.env"

[ -f "$SRC" ] || { echo "Not found: $SRC" >&2; exit 1; }
[ -d "$DEST_DIR" ] || { echo "Not found: $DEST_DIR — clone the repository first" >&2; exit 1; }

read_var() {
    # Last definition wins, matching how docker compose reads an env file.
    grep -E "^$1=" "$SRC" | tail -1 | cut -d= -f2- || true
}

SUPABASE_DB_PASSWORD=$(read_var SUPABASE_DB_PASSWORD)
EVO_DB_PASSWORD=$(read_var DB_PASSWORD)
REDIS_PASSWORD=$(read_var REDIS_PASSWORD)
ANON_KEY=$(read_var SUPABASE_ANON_KEY)
SERVICE_ROLE_KEY=$(read_var SUPABASE_SERVICE_ROLE_KEY)
API_HOST=$(read_var HOSTNAME_SUPABASE_ALT)
TZ_VALUE=$(read_var TZ)

for v in SUPABASE_DB_PASSWORD EVO_DB_PASSWORD REDIS_PASSWORD ANON_KEY SERVICE_ROLE_KEY API_HOST; do
    [ -n "${!v}" ] || { echo "Missing $v in $SRC" >&2; exit 1; }
done

APP_HOST="${APP_HOST:-odontobox.venn360.com}"

# Preserve a key already issued: regenerating it would orphan every paired
# WhatsApp instance, since the per-instance tokens are minted under it.
if [ -f "$DEST" ] && grep -qE "^EVOLUTION_GO_API_KEY=.+" "$DEST"; then
    EVOLUTION_GO_API_KEY=$(grep -E "^EVOLUTION_GO_API_KEY=" "$DEST" | tail -1 | cut -d= -f2-)
    echo "==> Keeping the existing EVOLUTION_GO_API_KEY"
else
    EVOLUTION_GO_API_KEY=$(openssl rand -base64 24 | tr '+/' '-_' | tr -d '=')
    echo "==> Generated a new EVOLUTION_GO_API_KEY"
fi

# Carry over the provider keys someone filled in by hand.
carry() {
    [ -f "$DEST" ] && grep -E "^$1=" "$DEST" | tail -1 | cut -d= -f2- || true
}
OPENAI_API_KEY=$(carry OPENAI_API_KEY)

umask 077
cat > "$DEST" <<ENVEOF
# Generated by infra/scripts/staycloud-env.sh — DO NOT COMMIT
# Secrets are read from $SRC; this file mirrors them for our own services.
# Generated at $(date -u +%Y-%m-%dT%H:%M:%SZ)

# ── Hosts ───────────────────────────────────────────────────
APP_HOST=$APP_HOST
API_HOST=$API_HOST
TZ=${TZ_VALUE:-America/Sao_Paulo}

# ── Database ────────────────────────────────────────────────
# Prisma talks to the Supabase Postgres, not the separate instance: Realtime only
# watches its own database, and the conversations inbox subscribes to
# postgres_changes on public.conversations and public.messages.
DATABASE_URL=postgresql://postgres:$SUPABASE_DB_PASSWORD@supabase-db:5432/postgres?schema=public

# ── Supabase ────────────────────────────────────────────────
NEXT_PUBLIC_SUPABASE_URL=https://$API_HOST
NEXT_PUBLIC_SUPABASE_ANON_KEY=$ANON_KEY
SUPABASE_SERVICE_ROLE_KEY=$SERVICE_ROLE_KEY
SUPABASE_DB_SCHEMA=public
NEXT_PUBLIC_SUPABASE_DB_SCHEMA=public
SUPABASE_STORAGE_BUCKET=attachments

# ── App ─────────────────────────────────────────────────────
NEXT_PUBLIC_APP_URL=https://$APP_HOST
NODE_ENV=production

# ── Queue ───────────────────────────────────────────────────
REDIS_URL=redis://default:$REDIS_PASSWORD@redis:6379

# ── Workers ─────────────────────────────────────────────────
WORKER_QUEUES=all
ENABLE_SCHEDULER=true
LOG_LEVEL=info
INBOUND_DEBOUNCE_SECONDS=4
AI_HISTORY_LIMIT=20
AI_RAG_CHUNKS=4
CONVERSATION_AUTOCLOSE_HOURS=0

# ── WhatsApp ────────────────────────────────────────────────
EVOLUTION_GO_URL=http://evolution-go:8080
EVOLUTION_GO_API_KEY=$EVOLUTION_GO_API_KEY
EVO_DB_PASSWORD=$EVO_DB_PASSWORD

# Providers post here. The internal address keeps the callback on the Compose
# network instead of leaving the host and returning through Traefik.
WEBHOOK_BASE_URL=http://app:3000

# ── OpenAI — fill this in by hand ───────────────────────────
# Chat do agente e embeddings do RAG. O projeto da chave precisa permitir os
# dois usos; uma allowlist só de chat derruba a base de conhecimento com 403.
OPENAI_API_KEY=$OPENAI_API_KEY

# ── Google Calendar — fill these in by hand ─────────────────
ENVEOF

chmod 600 "$DEST"
echo "==> Wrote $DEST (mode 600)"
echo
echo "    app  →  https://$APP_HOST"
echo "    api  →  https://$API_HOST"
echo
MISSING=""
for v in OPENAI_API_KEY; do
    [ -n "$(carry "$v")" ] || MISSING="$MISSING $v"
done
[ -n "$MISSING" ] && echo "    Still empty:$MISSING" || echo "    OpenAI key present."
