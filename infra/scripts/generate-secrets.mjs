#!/usr/bin/env node
/**
 * Generate the secrets the stack needs and write infra/.env.
 *
 * Self-hosted Supabase does not hand you an anon / service-role key: both are
 * JWTs you sign yourself with JWT_SECRET, with the roles and expiry Supabase
 * expects. Getting that wrong produces a stack that boots and then rejects every
 * request, so it is generated here rather than assembled by hand.
 *
 * Usage:
 *   node infra/scripts/generate-secrets.mjs --domain kaly.com.br [--force]
 */
import crypto from 'node:crypto'
import fs from 'node:fs'
import path from 'node:path'
import { renderTraefik } from './render-traefik.mjs'

const args = process.argv.slice(2)
function flag(name, fallback = undefined) {
    const i = args.indexOf(`--${name}`)
    if (i === -1) return fallback
    const value = args[i + 1]
    return value && !value.startsWith('--') ? value : true
}

const domain = flag('domain')
const force = Boolean(flag('force'))
const years = Number(flag('years', 10))

if (!domain || domain === true) {
    console.error('Usage: node infra/scripts/generate-secrets.mjs --domain <example.com> [--force] [--years 10]')
    process.exit(1)
}

const infraDir = path.resolve(import.meta.dirname, '..')
const envPath = path.join(infraDir, '.env')

if (fs.existsSync(envPath) && !force) {
    console.error(`Refusing to overwrite ${envPath}. Re-run with --force if that is what you want.`)
    console.error('Rotating these values invalidates every existing session and stored JWT.')
    process.exit(1)
}

/** URL-safe random string, suitable for passwords and API keys. */
const token = (bytes = 32) => crypto.randomBytes(bytes).toString('base64url')

/** Postgres password: alphanumeric only, since it travels inside a URL. */
const pgPassword = () => crypto.randomBytes(24).toString('hex')

const b64url = (input) => Buffer.from(input).toString('base64url')

/** Sign a Supabase-shaped HS256 JWT for the given role. */
function signJwt(role, secret, expiresInSeconds) {
    const header = { alg: 'HS256', typ: 'JWT' }
    const now = Math.floor(Date.now() / 1000)
    const payload = { role, iss: 'supabase', iat: now, exp: now + expiresInSeconds }

    const unsigned = `${b64url(JSON.stringify(header))}.${b64url(JSON.stringify(payload))}`
    const signature = crypto.createHmac('sha256', secret).update(unsigned).digest('base64url')

    return `${unsigned}.${signature}`
}

// Supabase requires a JWT secret of at least 32 characters.
const jwtSecret = token(32)
const expiry = years * 365 * 24 * 3600

const values = {
    '# ── Domain ─────────────────────────────────────────────': '',
    DOMAIN: domain,
    ACME_EMAIL: `admin@${domain}`,

    '# ── Postgres ───────────────────────────────────────────': '',
    POSTGRES_PASSWORD: pgPassword(),
    POSTGRES_DB: 'postgres',
    POSTGRES_PORT: '5432',
    POSTGRES_HOST: 'db',

    '# ── Supabase keys (derived from JWT_SECRET) ────────────': '',
    JWT_SECRET: jwtSecret,
    ANON_KEY: signJwt('anon', jwtSecret, expiry),
    SERVICE_ROLE_KEY: signJwt('service_role', jwtSecret, expiry),

    '# ── Supabase internals ─────────────────────────────────': '',
    SECRET_KEY_BASE: token(48),
    VAULT_ENC_KEY: token(24),
    DASHBOARD_USERNAME: 'admin',
    DASHBOARD_PASSWORD: token(18),
    POOLER_TENANT_ID: 'kaly',
    LOGFLARE_PUBLIC_ACCESS_TOKEN: token(24),
    LOGFLARE_PRIVATE_ACCESS_TOKEN: token(24),

    '# ── Redis ──────────────────────────────────────────────': '',
    REDIS_PASSWORD: token(24),

    '# ── Evolution Go (WhatsApp QR, whatsmeow) ──────────────': '',
    EVOLUTION_GO_API_KEY: token(24),

    '# ── Evolution API v2 (official Meta channel, opt-in) ───': '',
    EVOLUTION_API_KEY: token(24),
}

const lines = ['# Generated by infra/scripts/generate-secrets.mjs — DO NOT COMMIT', `# Generated at ${new Date().toISOString()}`, '']

for (const [key, value] of Object.entries(values)) {
    if (value === '') {
        lines.push('', key)
    } else {
        lines.push(`${key}=${value}`)
    }
}

lines.push(
    '',
    '# ── Filled in from the generated values above ──────────',
    '# These repeat values on purpose: the app and worker read them under',
    '# their own names, and keeping them explicit makes the wiring greppable.',
    '',
    `DATABASE_URL=postgresql://postgres:${values.POSTGRES_PASSWORD}@db:5432/postgres?schema=public`,
    `NEXT_PUBLIC_SUPABASE_URL=https://api.${domain}`,
    `NEXT_PUBLIC_SUPABASE_ANON_KEY=${values.ANON_KEY}`,
    `SUPABASE_SERVICE_ROLE_KEY=${values.SERVICE_ROLE_KEY}`,
    'SUPABASE_DB_SCHEMA=public',
    'NEXT_PUBLIC_SUPABASE_DB_SCHEMA=public',
    `NEXT_PUBLIC_APP_URL=https://app.${domain}`,
    `SITE_URL=https://app.${domain}`,
    `API_EXTERNAL_URL=https://api.${domain}`,
    `SUPABASE_PUBLIC_URL=https://api.${domain}`,
    '',
    `REDIS_URL=redis://default:${values.REDIS_PASSWORD}@redis:6379`,
    '',
    '# Evolution Go serves the QR channel. Internal only: it is not routed',
    '# through Traefik, and the one-time license activation at /manager goes',
    '# over an SSH tunnel (see infra/README.md).',
    `EVOLUTION_GO_URL=http://evolution-go:8080`,
    '',
    '# Where providers post their webhooks. The internal address keeps the',
    '# callback on the Compose network instead of leaving the host and coming',
    '# back in through Traefik.',
    `WEBHOOK_BASE_URL=http://app:3000`,
    '',
    '# Evolution API v2 — only used for the official Meta Cloud API channel,',
    '# started with: docker compose --profile business up -d',
    `EVOLUTION_API_URL=http://evolution-v2:8080`,
    `WEBHOOK_URL=http://app:3000/api/webhooks/evolution`,
    '',
    '# ── LLM providers — fill these in yourself ─────────────',
    'OPENAI_API_KEY=',
    'GOOGLE_AI_API_KEY=',
    'ANTHROPIC_API_KEY=',
    '',
    '# ── Google Calendar OAuth — fill these in yourself ─────',
    'GOOGLE_CLIENT_ID=',
    'GOOGLE_CLIENT_SECRET=',
    `GOOGLE_REDIRECT_URI=https://app.${domain}/api/integrations/google/callback`,
    ''
)

fs.writeFileSync(envPath, lines.join('\n'), { mode: 0o600 })

console.log(`Wrote ${envPath} (mode 0600)`)
console.log(`Wrote ${renderTraefik(domain)}`)
console.log('')
console.log('Studio login:')
console.log(`  user: ${values.DASHBOARD_USERNAME}`)
console.log(`  pass: ${values.DASHBOARD_PASSWORD}`)
console.log('')
console.log('Still to fill in by hand: OPENAI_API_KEY, GOOGLE_AI_API_KEY,')
console.log('ANTHROPIC_API_KEY, GOOGLE_CLIENT_ID, GOOGLE_CLIENT_SECRET.')
console.log('')
console.log('Keep a copy somewhere safe: regenerating JWT_SECRET invalidates')
console.log('every existing session and every key already handed out.')
